GEAR = {
    "en": {"high": "High", "low": "Low"},
    "de": {"high": "Hoch", "low": "Niedrig"},
    "zh-Hans": {"high": "高", "low": "低"},
    "es": {"high": "Alto", "low": "Bajo"},
    "fr": {"high": "Haut", "low": "Bas"},
}

NUMBER_KEYS = (
    "charge_current_alarm",
    "charge_current_limit",
    "discharge_current_alarm",
    "discharge_current_limit",
)
SWITCH_KEYS = (
    "status_charge_enabled",
    "status_discharge_enabled",
    "status_current_limit_enabled",
)


def names(mapping):
    return {key: {"name": value} for key, value in mapping.items()}


def entity_block(lang):
    extra = json.loads((ROOT.parents[1] / "scripts" / "config_labels.json").read_text())
    labels = dict(PACK[lang])
    labels.update(extra[lang])
    sensors = names(labels)
    sensors.update(names(TOTAL[lang]))
    number_keys = list(NUMBER_KEYS) + [key for key in extra["en"] if key not in NUMBER_KEYS]
    return {
        "sensor": sensors,
        "binary_sensor": names(BINARY[lang]),
        "number": names({key: labels[key] for key in number_keys}),
        "switch": names({key: BINARY[lang][key] for key in SWITCH_KEYS}),
        "select": {
            "limiter_gear": {
                "name": labels["limiter_gear"],
                "state": GEAR[lang],
            }
        },
    }


def main():
    strings_path = ROOT / "strings.json"
    strings = json.loads(strings_path.read_text())
    strings["entity"] = entity_block("en")
    strings_path.write_text(json.dumps(strings, ensure_ascii=False, indent=2) + "\n")

    translations = ROOT / "translations"
    translations.mkdir(exist_ok=True)
    for lang in ("en", "de", "zh-Hans", "es", "fr"):
        path = translations / f"{lang}.json"
        data = json.loads(path.read_text()) if path.exists() else {}
        data["entity"] = entity_block(lang)
        if lang == "en" and "config" not in data:
            data["config"] = strings["config"]
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")


if __name__ == "__main__":
    main()
